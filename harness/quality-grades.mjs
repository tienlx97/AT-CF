#!/usr/bin/env node
// Measures every source unit and writes harness/quality-grades.json (ENTROPY.md):
// grades are measurements, not opinions (golden rule #9).
//
//   node harness/quality-grades.mjs                       # runs ESLint itself (needs node_modules)
//   node harness/quality-grades.mjs --eslint lint.json    # reuse `eslint src --format json` output
//   node harness/quality-grades.mjs --check               # exit 1 if the stored grades are out of date
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const RUBRIC = {
  A: 'canonical: no lint warnings at all, no source file over 800 lines, at least 1 test per 7 source files (units of 3 files or fewer exempt)',
  B: 'acceptable, minor drift: anything between A and C (e.g. only autofixable lint warnings, one or two large files, too few tests)',
  C: 'known debt, do not copy: 5+ non-autofix lint warnings, or 3+ source files over 800 lines, or no tests in a unit of 10+ source files',
};
const BIG_FILE_LINES = 800;
const AUTOFIX_RULES = new Set(); // rule ids whose warnings `eslint --fix` clears

// Units graded on their own; a file belongs to the longest matching unit.
export function units(root) {
  const list = ['src/app'].filter((unit) => existsSync(join(root, unit)));
  for (const base of ['src/features', 'src/shared']) {
    if (!existsSync(join(root, base))) continue;
    for (const name of readdirSync(join(root, base))) if (statSync(join(root, base, name)).isDirectory()) list.push(`${base}/${name}`);
  }
  return list.sort();
}

export function grade(m) {
  const testsNeeded = m.sourceFiles > 3 ? Math.ceil(m.sourceFiles / 7) : 0;
  if (m.lintWarnings >= 5 || m.bigFiles >= 3 || (m.sourceFiles >= 10 && m.testFiles === 0)) return 'C';
  if (m.lintWarnings === 0 && m.autofixWarnings === 0 && m.bigFiles === 0 && m.testFiles >= testsNeeded) return 'A';
  return 'B';
}

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => (entry.isDirectory() ? walk(join(directory, entry.name)) : [join(directory, entry.name)]));
}

export function measure(root, lintResults) {
  const posix = (file) => relative(root, file).split(sep).join('/');
  const lint = new Map();
  for (const result of lintResults) {
    // ESLint may have run in another checkout (the WSL gate clone): keep the path from src/ on.
    const at = result.filePath.replace(/\\/g, '/').lastIndexOf('/src/');
    lint.set(result.filePath.replace(/\\/g, '/').slice(at + 1), result.messages);
  }
  const list = units(root);
  const owner = (file) => list.filter((unit) => file.startsWith(`${unit}/`)).sort((a, b) => b.length - a.length)[0];
  const metrics = Object.fromEntries(list.map((unit) => [unit, { sourceFiles: 0, testFiles: 0, lines: 0, lintWarnings: 0, autofixWarnings: 0, bigFiles: 0 }]));
  for (const file of walk(join(root, 'src')).map(posix).filter((name) => /\.(js|jsx|mjs)$/.test(name))) {
    const unit = owner(file);
    if (!unit) continue;
    const m = metrics[unit];
    for (const message of lint.get(file) ?? []) {
      if (AUTOFIX_RULES.has(message.ruleId)) m.autofixWarnings++;
      else m.lintWarnings++;
    }
    if (/\.test\.(js|jsx|mjs)$/.test(file)) {
      m.testFiles++;
      continue;
    }
    const text = readFileSync(join(root, file), 'utf8');
    const lines = text.split('\n').length;
    m.sourceFiles++;
    m.lines += lines;
    if (lines > BIG_FILE_LINES) m.bigFiles++;
  }
  return metrics;
}

export function document(metrics, measuredAt) {
  const grades = Object.fromEntries(Object.entries(metrics).map(([unit, m]) => [unit, grade(m)]));
  return {
    $comment: 'Generated by `node harness/quality-grades.mjs` (see harness/ENTROPY.md). A = canonical (copy patterns), B = acceptable, C = debt (do not replicate; improve on touch). A file takes the grade of its longest matching unit.',
    rubric: RUBRIC,
    grades,
    metrics,
    updated: measuredAt,
  };
}

function main(argv) {
  const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
  const at = argv.indexOf('--eslint');
  let lintResults;
  if (at !== -1) lintResults = JSON.parse(readFileSync(argv[at + 1], 'utf8'));
  else {
    if (!existsSync(join(root, 'node_modules'))) {
      console.error('quality-grades: no node_modules here; run `pnpm install`, or pass --eslint <eslint src --format json output>');
      process.exit(2);
    }
    const out = execFileSync('pnpm', ['exec', 'eslint', 'src', '--format', 'json'], { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: process.platform === 'win32' });
    lintResults = JSON.parse(out);
  }
  const file = join(root, 'harness/quality-grades.json');
  const today = new Date().toISOString().slice(0, 10);
  const next = document(measure(root, lintResults), today);
  if (argv.includes('--check')) {
    const stored = JSON.parse(readFileSync(file, 'utf8'));
    const drift = Object.keys({ ...stored.grades, ...next.grades }).filter((unit) => stored.grades[unit] !== next.grades[unit]);
    if (drift.length) {
      console.error(`quality-grades: out of date for ${drift.map((unit) => `${unit} (${stored.grades[unit] ?? '-'} → ${next.grades[unit] ?? '-'})`).join(', ')}`);
      process.exit(1);
    }
    console.log('quality-grades: up to date');
    return;
  }
  writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`);
  for (const [unit, value] of Object.entries(next.grades)) console.log(`${value}  ${unit}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
